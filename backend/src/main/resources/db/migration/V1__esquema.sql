-- Modelo de datos del motor de horarios (DER del Módulo 2 en su versión final).
-- SQL compatible con PostgreSQL 16 y con H2 en modo PostgreSQL.

CREATE TABLE franja_horaria (
    id_franja    SMALLINT    PRIMARY KEY,
    dia          VARCHAR(10) NOT NULL,
    hora_inicio  TIME        NOT NULL,
    hora_fin     TIME        NOT NULL,
    CONSTRAINT ck_franja_dia CHECK (dia IN ('LUNES','MARTES','MIERCOLES','JUEVES','VIERNES','SABADO')),
    CONSTRAINT uq_franja UNIQUE (dia, hora_inicio)
);

CREATE TABLE docente (
    id_docente   VARCHAR(10) PRIMARY KEY,
    nombre       VARCHAR(80) NOT NULL,
    dedicacion   VARCHAR(20),
    escalafon    VARCHAR(30)
);

-- La disponibilidad se guarda por día y hora de inicio y no por índice de franja.
-- Así sobrevive a un cambio de la grilla y se traduce al índice vigente al generar.
CREATE TABLE disponibilidad_docente (
    id_docente   VARCHAR(10) NOT NULL REFERENCES docente (id_docente),
    dia          VARCHAR(10) NOT NULL,
    hora_inicio  TIME        NOT NULL,
    PRIMARY KEY (id_docente, dia, hora_inicio)
);

CREATE TABLE aula (
    id_aula      VARCHAR(10) PRIMARY KEY,
    capacidad    SMALLINT    NOT NULL,
    CONSTRAINT ck_aula_capacidad CHECK (capacidad > 0)
);

CREATE TABLE caracteristica (
    id_caracteristica VARCHAR(20) PRIMARY KEY,
    descripcion       VARCHAR(60) NOT NULL
);

CREATE TABLE aula_caracteristica (
    id_aula           VARCHAR(10) NOT NULL REFERENCES aula (id_aula),
    id_caracteristica VARCHAR(20) NOT NULL REFERENCES caracteristica (id_caracteristica),
    PRIMARY KEY (id_aula, id_caracteristica)
);

CREATE TABLE curso (
    id_curso               VARCHAR(10) PRIMARY KEY,
    nombre                 VARCHAR(80) NOT NULL,
    num_sesiones_semanales SMALLINT    NOT NULL,
    CONSTRAINT ck_curso_sesiones CHECK (num_sesiones_semanales BETWEEN 1 AND 4)
);

CREATE TABLE curso_requisito_aula (
    id_curso          VARCHAR(10) NOT NULL REFERENCES curso (id_curso),
    id_caracteristica VARCHAR(20) NOT NULL REFERENCES caracteristica (id_caracteristica),
    PRIMARY KEY (id_curso, id_caracteristica)
);

CREATE TABLE habilitacion_docente (
    id_curso   VARCHAR(10) NOT NULL REFERENCES curso (id_curso),
    id_docente VARCHAR(10) NOT NULL REFERENCES docente (id_docente),
    PRIMARY KEY (id_curso, id_docente)
);

CREATE TABLE grupo (
    id_grupo     VARCHAR(15) PRIMARY KEY,
    id_curso     VARCHAR(10) NOT NULL REFERENCES curso (id_curso),
    matriculados SMALLINT    NOT NULL,
    CONSTRAINT ck_grupo_matriculados CHECK (matriculados >= 0)
);

CREATE TABLE sesion (
    id_sesion     VARCHAR(20) PRIMARY KEY,
    id_grupo      VARCHAR(15) NOT NULL REFERENCES grupo (id_grupo),
    numero_sesion SMALLINT    NOT NULL,
    CONSTRAINT uq_sesion UNIQUE (id_grupo, numero_sesion)
);

CREATE TABLE usuario (
    id_usuario      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario  VARCHAR(40)  NOT NULL,
    hash_contrasena VARCHAR(100) NOT NULL,
    rol             VARCHAR(15)  NOT NULL,
    CONSTRAINT uq_usuario_nombre UNIQUE (nombre_usuario),
    CONSTRAINT ck_usuario_rol CHECK (rol = 'ADMIN')
);

CREATE TABLE ejecucion_horario (
    id_ejecucion     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario       INTEGER     NOT NULL REFERENCES usuario (id_usuario),
    fecha_hora       TIMESTAMP   NOT NULL,
    estado           VARCHAR(10) NOT NULL,
    nodos_explorados BIGINT      NOT NULL,
    duracion_ms      INTEGER     NOT NULL,
    CONSTRAINT ck_ejecucion_estado CHECK (estado IN ('COMPLETO','PARCIAL'))
);

-- Una fila por sesión ubicada en una ejecución. Las dos restricciones UNIQUE hacen que la base
-- de datos rechace por su cuenta un choque de docente (RD-01) o de aula (RD-02).
CREATE TABLE asignacion (
    id_ejecucion INTEGER     NOT NULL REFERENCES ejecucion_horario (id_ejecucion),
    id_sesion    VARCHAR(20) NOT NULL REFERENCES sesion (id_sesion),
    id_docente   VARCHAR(10) NOT NULL REFERENCES docente (id_docente),
    id_aula      VARCHAR(10) NOT NULL REFERENCES aula (id_aula),
    dia          VARCHAR(10) NOT NULL,
    hora_inicio  TIME        NOT NULL,
    hora_fin     TIME        NOT NULL,
    PRIMARY KEY (id_ejecucion, id_sesion),
    CONSTRAINT uq_asignacion_docente_franja UNIQUE (id_ejecucion, id_docente, dia, hora_inicio),
    CONSTRAINT uq_asignacion_aula_franja UNIQUE (id_ejecucion, id_aula, dia, hora_inicio)
);

CREATE TABLE restriccion (
    codigo      VARCHAR(6)   PRIMARY KEY,
    tipo        VARCHAR(10)  NOT NULL,
    descripcion VARCHAR(160) NOT NULL,
    CONSTRAINT ck_restriccion_tipo CHECK (tipo IN ('DURA','VALIDACION'))
);

CREATE TABLE conflicto (
    id_conflicto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ejecucion INTEGER     NOT NULL REFERENCES ejecucion_horario (id_ejecucion),
    id_sesion    VARCHAR(20) NOT NULL REFERENCES sesion (id_sesion),
    CONSTRAINT uq_conflicto UNIQUE (id_ejecucion, id_sesion)
);

CREATE TABLE conflicto_restriccion (
    id_conflicto      INTEGER    NOT NULL REFERENCES conflicto (id_conflicto),
    codigo            VARCHAR(6) NOT NULL REFERENCES restriccion (codigo),
    tuplas_bloqueadas INTEGER    NOT NULL,
    PRIMARY KEY (id_conflicto, codigo),
    CONSTRAINT ck_conflicto_tuplas CHECK (tuplas_bloqueadas > 0)
);

CREATE TABLE hallazgo_validacion (
    id_ejecucion INTEGER      NOT NULL REFERENCES ejecucion_horario (id_ejecucion),
    id_grupo     VARCHAR(15)  NOT NULL REFERENCES grupo (id_grupo),
    codigo       VARCHAR(6)   NOT NULL REFERENCES restriccion (codigo),
    mensaje      VARCHAR(200) NOT NULL,
    PRIMARY KEY (id_ejecucion, id_grupo, codigo)
);

CREATE TABLE parametro_configuracion (
    clave     VARCHAR(30) PRIMARY KEY,
    valor     VARCHAR(30) NOT NULL,
    tipo_dato VARCHAR(10) NOT NULL,
    CONSTRAINT ck_parametro_tipo CHECK (tipo_dato IN ('ENTERO','DECIMAL','HORA'))
);
